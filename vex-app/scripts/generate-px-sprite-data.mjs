#!/usr/bin/env node
/**
 * Regenerates src/renderer/components/icons/px/px-sprite-data.ts from
 * px/sprite.svg. The renderer mounts the sprite as JSX from this data (no
 * dangerouslySetInnerHTML, CSP-clean). Run after editing sprite.svg:
 *   node scripts/generate-px-sprite-data.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const pxDir = path.join(here, "..", "src", "renderer", "components", "icons", "px");
const source = readFileSync(path.join(pxDir, "sprite.svg"), "utf8");

const symbols = [];
for (const m of source.matchAll(/<symbol id="(px-[a-z0-9-]+)" viewBox="([^"]+)" fill="currentColor" shape-rendering="crispEdges">(.*?)<\/symbol>/g)) {
  const rects = [];
  for (const r of m[3].matchAll(/<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"\/>/g)) {
    rects.push([Number(r[1]), Number(r[2]), Number(r[3]), Number(r[4])]);
  }
  const rest = m[3].replace(/<rect [^>]*\/>/g, "");
  if (rest.trim() !== "") throw new Error(`${m[1]}: unexpected markup ${rest}`);
  symbols.push({ id: m[1], viewBox: m[2], rects });
}
const declared = (source.match(/<symbol /g) ?? []).length;
if (symbols.length !== declared) throw new Error(`parsed ${symbols.length} of ${declared} symbols`);

const lines = symbols.map(
  (s) => `  { id: "${s.id}", viewBox: "${s.viewBox}", rects: [${s.rects.map((r) => `[${r.join(", ")}]`).join(", ")}] },`,
);
const out = `/**
 * GENERATED by scripts/generate-px-sprite-data.mjs from px/sprite.svg. Do not
 * edit by hand. Each rect is [x, y, width, height].
 */

export type PxRect = readonly [x: number, y: number, width: number, height: number];

export interface PxSymbolData {
  readonly id: string;
  readonly viewBox: string;
  readonly rects: readonly PxRect[];
}

export const PX_SPRITE_DATA: readonly PxSymbolData[] = [
${lines.join("\n")}
];
`;
writeFileSync(path.join(pxDir, "px-sprite-data.ts"), out);
console.log(`wrote ${symbols.length} symbols`);
