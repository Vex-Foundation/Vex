/**
 * Integration: migration 096 applies cleanly to a schema that stops at 095, and
 * its CHECKs accept and reject the rows they are meant to.
 *
 * WHY THIS EXISTS, sibling of `094-pools-launch-attribution.int.test.ts`.
 * `globalSetup` runs the whole chain 001..096 in one pass on an empty database,
 * which proves the file is valid SQL and nothing more. It does NOT prove:
 *
 *   1. that none of 096's objects already exist at 095 - a collision with a
 *      concurrent branch would show up here and nowhere else;
 *   2. that the runner applies 096 as an INCREMENT to a populated schema rather
 *      than as step 96 of a fresh chain;
 *   3. that the table's own CHECK constraints admit exactly the rows the wrap
 *      lifecycle produces and refuse the rest.
 *
 * MECHANISM, unchanged from the 094 template: a second database inside the SAME
 * container the suite already runs, the real `runMigrationsWithProgress`
 * pointed at a temp directory holding only the files at or below 095, and then
 * 096 copied in and the runner invoked again. Nothing is stubbed: same runner,
 * same files, same Postgres.
 *
 * WHICH DIRECTORY THE FILES COME FROM, stated precisely because an earlier
 * revision of this docblock claimed the wrong one. `getVexAgentMigrationsDir()`
 * resolves the directory THE ENGINE RUNTIME ITSELF loads migrations from:
 * `dist/vex-agent/db/migrations` when the package has been built, otherwise the
 * canonical source tree `src/vex-agent/db/migrations` (see
 * `src/utils/package-assets.ts`). It is NOT the desktop app's packaged mirror.
 * That mirror is `vex-app/resources/migrations/`, a git-ignored artifact
 * generated by `vex-app/scripts/copy-migrations.mjs` (wired as vex-app's
 * `prebuild`/`predev`) and packed by electron-builder's `extraResources`.
 *
 * The mirror IS exercised, by the last describe in this file, but only when it
 * exists: a dev checkout that has never run a vex-app build or `dev` has no
 * mirror at all, and a test suite that required an ungenerated artifact would
 * fail for the wrong reason. That describe is therefore gated with the repo's
 * existing `describe.skipIf` idiom and names its remedy in its own title, so a
 * skip is visible in the reporter rather than silent.
 *
 * DELIBERATE DEVIATION on the CHECK half. The sibling unit suites evaluate a
 * constraint body with `db/repos/_sql-check-eval.ts` against concrete rows.
 * That evaluator's grammar is `IS [NOT] NULL`, `=`, `<>` and `IN` over plain
 * columns - it models neither the `payload_json ->> 'key'` extraction nor the
 * `LIKE` prefix match that 096's direction/payload and payload/target
 * constraints are written in, and widening it for one caller would put a second
 * partial SQL implementation in the test tree. So the constraints are evaluated
 * HERE by the authority itself: every row below is a real INSERT against a real
 * PostgreSQL that has migration 096 applied, and "would Postgres accept this
 * row?" is answered by Postgres. That is strictly stronger than the evaluator,
 * not weaker.
 */

