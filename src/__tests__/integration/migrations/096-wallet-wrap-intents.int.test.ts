/** What the ENGINE runtime loads: `dist/` when built, else the source tree. */
const SOURCE_DIR = getVexAgentMigrationsDir();
/** What the DESKTOP APP ships: generated, git-ignored, absent until built. */
const MIRROR_DIR = path.join(getPackageRoot(), "vex-app", "resources", "migrations");
const TARGET_DB = "vex_096_probe";
const MIRROR_DB = "vex_096_mirror";
const MIGRATION_096 = "096_wallet_wrap_intents.sql";
const MIRROR_PRESENT = existsSync(path.join(MIRROR_DIR, MIGRATION_096));

const SESSION = "session-096-probe";
const WALLET = "0xaaaabbbbccccddddeeeeffff0000111122223333";
const WETH = "0x4200000000000000000000000000000000000006";
const OTHER_CONTRACT = "0xc02aaa39b223fe8d0a0e5c4f27ead9083c756cc2";
const AMOUNT_RAW = "2500000000000000000";
const DEPOSIT_SELECTOR = "0xd0e30db0";
const WITHDRAW_CALLDATA = `0x2e1a7d4d${BigInt(AMOUNT_RAW).toString(16).padStart(64, "0")}`;
const TX_HASH = "0xaaaa000000000000000000000000000000000000000000000000000000000001";
const DIGEST = "d".repeat(64);

let pool: pg.Pool;
let stagingDir: string;

/**
 * Migration filenames at or below `maxVersion`, in application order. The
 * filter is the runner's own discovery rule, and the same one
 * `copy-migrations.mjs` mirrors with.
 */
function filesUpToIn(dir: string, maxVersion: number): string[] {
  return readdirSync(dir)
    .filter((f) => f.endsWith(".sql") && /^\d{3}_/.test(f))
    .filter((f) => parseInt(f.slice(0, 3), 10) <= maxVersion)
    .sort();
}

function filesUpTo(maxVersion: number): string[] {
  return filesUpToIn(SOURCE_DIR, maxVersion);
}

function stage(files: readonly string[]): void {
  for (const f of files) copyFileSync(path.join(SOURCE_DIR, f), path.join(stagingDir, f));
}

/**
 * The single row a one-row probe query must have returned. A throwing accessor
 * rather than a non-null assertion: "the catalog query matched nothing" is
 * itself a meaningful failure here and should be named.
 */
function onlyRow<T extends pg.QueryResultRow>(result: pg.QueryResult<T>, what: string): T {
  const row = result.rows[0];
  if (row === undefined) throw new Error(`expected exactly one row for ${what}, got none`);
  return row;
}

async function constraintNames(target: pg.Pool = pool): Promise<string[]> {
  const res = await target.query<{ conname: string }>(
    `SELECT conname FROM pg_constraint
      WHERE conrelid = 'wallet_wrap_intents'::regclass AND contype = 'c'`,
  );
  return res.rows.map((r) => r.conname);
}

interface IntentRow {
  readonly direction: "wrap" | "unwrap";
  readonly wrappedNativeAddress: string;
  readonly amountRaw: string;
  readonly payload: Record<string, string>;
  readonly status: string;
  readonly failureStage: string | null;
  readonly txHash: string | null;
}

/** A VALID wrap row, in every field the CHECKs read. Overridden per case. */
function validWrap(overrides: Partial<IntentRow> = {}): IntentRow {
  return {
    direction: "wrap",
    wrappedNativeAddress: WETH,
    amountRaw: AMOUNT_RAW,
    payload: { to: WETH, data: DEPOSIT_SELECTOR, valueWei: AMOUNT_RAW },
    status: "pending",
    failureStage: null,
    txHash: null,
    ...overrides,
  };
}

/** A VALID unwrap row: the amount is in the calldata and the value is zero. */
function validUnwrap(overrides: Partial<IntentRow> = {}): IntentRow {
  return validWrap({
    direction: "unwrap",
    payload: { to: WETH, data: WITHDRAW_CALLDATA, valueWei: "0" },
    ...overrides,
  });
}

let nextId = 0;

/** Insert one row. Resolves on acceptance, rejects with Postgres's own error. */
async function insertIntent(row: IntentRow, target: pg.Pool = pool): Promise<void> {
  nextId += 1;
  await target.query(
    `INSERT INTO wallet_wrap_intents (
       intent_id, session_id, wallet_address, chain_alias, chain_id, direction,
       wrapped_native_address, wrapped_native_symbol, wrapped_native_decimals,
       amount_raw, payload_json, preview_json, fee_bounds_json,
       proposal_digest, proposal_digest_version,
       status, failure_stage, tx_hash, expires_at
     ) VALUES (
       $1, $2, $3, 'base', 8453, $4,
       $5, 'WETH', 18,
       $6, $7::jsonb, $8::jsonb, $9::jsonb,
       $10, 'v1',
       $11, $12, $13, NOW() + INTERVAL '10 minutes'
     )`,
    [
      `wrp-096-${nextId}`,
      SESSION,
      WALLET,
      row.direction,
      row.wrappedNativeAddress,
      row.amountRaw,
      JSON.stringify(row.payload),
      JSON.stringify({ label: "Wrap 2.5 ETH", criticalArgs: { chain: "base" } }),
      JSON.stringify({
        mode: "eip1559",
        gasLimit: "60000",
        maxFeePerGasWei: "2000000000",
        maxPriorityFeePerGasWei: "1000000000",
        maxTotalFeeWei: "120000000000000",
      }),
      DIGEST,
      row.status,
      row.failureStage,
      row.txHash,
    ],
  );
}

/** The row is accepted. */
async function expectAccepted(row: IntentRow, target: pg.Pool = pool): Promise<void> {
  await expect(insertIntent(row, target)).resolves.toBeUndefined();
}

/** The row is refused by a CHECK, and by a CHECK specifically (SQLSTATE 23514). */
async function expectRejected(row: IntentRow, target: pg.Pool = pool): Promise<void> {
  const error = await insertIntent(row, target).then(
    () => null,
    (err: unknown) => err,
  );
  expect(error, "the row was ACCEPTED but must be refused").not.toBeNull();
  expect((error as { code?: string }).code, "must be a CHECK violation").toBe("23514");
}

